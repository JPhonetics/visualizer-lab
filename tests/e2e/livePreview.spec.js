import { expect, test } from "@playwright/test"

test("renders editor layers, reloads scripts and keeps execution inside the iframe", async ({ page }) => {
    await page.goto("/frontend")
    const frame = page.frameLocator(".preview-frame")
    await page.getByRole("textbox", { name: "HTML code editor" }).fill('<p id="result">Hello</p><script>document.body.dataset.inlineRan = "yes"</script>')
    await expect(frame.locator("#result")).toHaveText("Hello")
    await expect(frame.locator("body")).toHaveAttribute("data-inline-ran", "yes")
    await page.getByRole("tab", { name: "CSS", exact: true }).click()
    await page.getByRole("textbox", { name: "CSS code editor" }).fill("#result { color: rgb(0, 128, 0); }")
    await expect(frame.locator("#result")).toHaveCSS("color", "rgb(0, 128, 0)")
    await page.getByRole("button", { name: "CSS", exact: true }).click()
    await expect(frame.locator("#result")).toHaveCSS("color", "rgb(0, 0, 0)")
    await page.getByRole("button", { name: "CSS", exact: true }).click()
    await expect(frame.locator("#result")).toHaveCSS("color", "rgb(0, 128, 0)")
    await page.getByRole("tab", { name: "JavaScript", exact: true }).click()
    await page.getByRole("textbox", { name: "JavaScript code editor" }).fill(`
        document.querySelector("#result").textContent = "JS ran";
        try { parent.document.body.dataset.previewEscaped = "yes"; }
        catch { document.body.dataset.parentBlocked = "yes"; }
    `)
    await expect(frame.locator("#result")).toHaveText("JS ran")
    await expect(frame.locator("body")).toHaveAttribute("data-parent-blocked", "yes")
    expect(await page.locator("body").getAttribute("data-preview-escaped")).toBeNull()
    await expect(page.locator(".preview-frame")).toHaveAttribute("sandbox", "allow-scripts")
    await frame.locator("#result").evaluate(el => { el.textContent = "mutated" })
    await page.getByRole("button", { name: "Reload preview" }).click()
    await expect(frame.locator("#result")).toHaveText("JS ran")
    await page.getByRole("button", { name: "JS", exact: true }).click()
    await expect(page.locator(".preview-frame")).toHaveAttribute("sandbox", "")
    await expect(frame.locator("#result")).toHaveText("Hello")
    expect(await frame.locator("body").getAttribute("data-inline-ran")).toBeNull()
    expect(await frame.locator("body").getAttribute("data-parent-blocked")).toBeNull()
    await page.getByRole("button", { name: "JS", exact: true }).click()
    await expect(frame.locator("#result")).toHaveText("JS ran")
})

test("standalone receives a fixed snapshot without source in URLs or storage", async ({ page }) => {
    await page.goto("/frontend")
    const html = page.getByRole("textbox", { name: "HTML code editor" })
    await html.fill("<h1>Initial snapshot</h1>")
    const opened = page.waitForEvent("popup")
    await page.getByRole("button", { name: "Open New Tab" }).click()
    const popup = await opened
    const frame = popup.frameLocator(".preview-frame")
    await expect(frame.getByRole("heading")).toHaveText("Initial snapshot")
    expect(popup.url()).not.toContain("Initial")
    const snapshots = await popup.evaluate(() => ({ local: { ...localStorage }, session: { ...sessionStorage } }))
    expect(JSON.stringify(snapshots)).not.toContain("Initial snapshot")
    await html.fill("<h1>Changed workspace</h1>")
    await expect(page.frameLocator(".preview-frame").getByRole("heading")).toHaveText("Changed workspace")
    await expect(frame.getByRole("heading")).toHaveText("Initial snapshot")
    await page.getByRole("button", { name: "Collapse Preview" }).click()
    await popup.reload()
    await expect(frame.getByRole("heading")).toHaveText("Initial snapshot")
    await page.close()
    await expect(frame.getByRole("heading")).toHaveText("Initial snapshot")
    await popup.reload()
    await expect(popup.getByRole("alert")).toContainText("snapshot is unavailable")
})
