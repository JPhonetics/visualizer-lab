import { expect, test } from "@playwright/test"

async function seed(page, count) {
    await page.addInitScript(({ count }) => {
        if (localStorage.getItem("visualizerLab.projects.v1")) return
        const sources = { html: "", css: "", javascript: "" }
        localStorage.setItem("visualizerLab.projects.v1", JSON.stringify({ version: 1,
            draft: { name: "Untitled", savedId: null, sources, updatedAt: null },
            saved: Array.from({ length: count }, (_, index) => ({ id: `project-${index + 1}`, name: `Example ${index + 1}`, sources, updatedAt: "2026-10-29T12:00:00Z" })),
        }))
    }, { count })
    await page.goto("/frontend")
}

test("many saved entries scroll without shrinking Templates and still allow pointer resizing", async ({ page }) => {
    await seed(page, 25)
    const dock = page.locator(".templates-dock")
    await expect(dock).toHaveCSS("height", "180px")
    const list = page.getByRole("list", { name: "Saved work list" })
    expect(await list.evaluate(el => el.scrollHeight > el.clientHeight)).toBe(true)
    const handle = page.getByRole("separator", { name: "Templates height" })
    const box = await handle.boundingBox()
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
    await page.mouse.down()
    await page.mouse.move(box.x + box.width / 2, box.y - 80, { steps: 12 })
    await page.mouse.up()
    expect(parseFloat(await dock.evaluate(el => getComputedStyle(el).height))).toBeGreaterThan(240)
    await list.evaluate(el => { el.scrollTop = el.scrollHeight })
    await expect(page.getByRole("button", { name: "Open Example 25", exact: true })).toBeInViewport()
    await page.reload()
    expect(parseFloat(await dock.evaluate(el => getComputedStyle(el).height))).toBeGreaterThan(240)
    await page.setViewportSize({ width: 800, height: 500 })
    await expect(handle).toBeInViewport()
})

test("numbering and tile/keyboard reorder persist, and search cannot reorder a subset", async ({ page }) => {
    // Keep both endpoints visible: dragTo scrolls each endpoint before dragging.
    await page.setViewportSize({ width: 1280, height: 1000 })
    await seed(page, 4)
    const list = page.getByRole("list", { name: "Saved work list" })
    await page.getByRole("button", { name: "Reorder saved work" }).click()
    await expect(page.getByRole("searchbox", { name: "Search saved work" })).toBeDisabled()
    const down = page.getByRole("button", { name: "Move Example 1 down", exact: true })
    await down.focus()
    await down.press("Enter")
    await expect(list.locator("li").nth(1)).toContainText("Example 1")
    await expect(list.locator("li").nth(1)).toHaveClass(/is-moved/)
    await expect(page.getByRole("status", { name: "Saved work order" })).toHaveText("Example 1: 1 → 2.")
    await expect(list.locator("li").nth(1).locator(".project-order-number")).toHaveText("2.")
    await page.getByRole("listitem", { name: "Example 4", exact: true }).dragTo(list.locator("li").first(), { sourcePosition: { x: 16, y: 12 } })
    await expect(list.locator("li").first()).toContainText("Example 4")
    await expect(list.locator("li").first()).toHaveClass(/is-moved/)
    await expect(list.locator("li.is-dragging, li.is-drop-before, li.is-drop-after")).toHaveCount(0)
    await expect(list.locator("li").first().locator(".project-order-number")).toHaveText("1.")
    await page.getByRole("button", { name: "Reorder saved work" }).click()
    await expect(page.getByRole("button", { name: "Open Example 4", exact: true })).toBeVisible()
    await page.reload()
    await expect(list.locator("li").first()).toContainText("Example 4")
    await expect(list.locator("li").nth(2)).toContainText("Example 1")
    await page.getByRole("searchbox", { name: "Search saved work" }).fill("Example 1")
    await expect(list.locator("li")).toHaveCount(1)
    await expect(list.locator(".project-order-number")).toHaveText("3.")
    await expect(page.getByRole("button", { name: "Reorder saved work" })).toBeDisabled()
})

test("tile drag feedback shows insertion direction and double-up moves to top", async ({ page }) => {
    await page.setViewportSize({ width: 1280, height: 1100 })
    await seed(page, 4)
    await page.getByRole("button", { name: "Reorder saved work" }).click()
    const list = page.getByRole("list", { name: "Saved work list" })
    const source = await page.getByRole("listitem", { name: "Example 4", exact: true }).boundingBox()
    const target = await list.locator("li").first().boundingBox()
    await page.mouse.move(source.x + 16, source.y + 12)
    await page.mouse.down()
    await page.mouse.move(source.x + 16, source.y - 12, { steps: 5 })
    await page.mouse.move(target.x + target.width / 2, target.y + target.height / 2, { steps: 12 })
    await page.mouse.move(target.x + target.width / 2 + 1, target.y + target.height / 2)
    await expect(list.locator("li.is-dragging")).toContainText("Example 4")
    await expect(list.locator("li.is-drop-before")).toContainText("Example 1")
    await expect(page.getByRole("status", { name: "Saved work order" })).toHaveText("Drop at position 1")
    await page.mouse.up()
    await expect(list.locator("li").first()).toContainText("Example 4")
    await page.getByRole("button", { name: "Move Example 3 to top", exact: true }).click()
    await expect(list.locator("li").first()).toContainText("Example 3")
    await expect(list.locator("li").first()).toHaveClass(/is-moved/)
    await expect(page.getByRole("status", { name: "Saved work order" })).toHaveText("Example 3: 4 → 1.")
    await expect(page.getByRole("button", { name: "Move Example 3 to top", exact: true })).toBeDisabled()
    await expect(page.getByRole("listitem", { name: "Example 3", exact: true })).toBeFocused()
    await page.reload()
    await expect(list.locator("li").first()).toContainText("Example 3")
})

test("dragging an arrow control does not start a tile reorder", async ({ page }) => {
    await page.setViewportSize({ width: 1280, height: 1100 })
    await seed(page, 4)
    await page.getByRole("button", { name: "Reorder saved work" }).click()
    const list = page.getByRole("list", { name: "Saved work list" })
    await page.getByRole("button", { name: "Move Example 4 up", exact: true }).dragTo(list.locator("li").first())
    await expect(list.locator("li").first()).toContainText("Example 1")
    await expect(list.locator("li").last()).toContainText("Example 4")
    await expect(list.locator("li.is-dragging")).toHaveCount(0)
    await expect(list.locator("li").first()).toHaveAttribute("draggable", "true")
    await page.getByRole("button", { name: "Reorder saved work" }).click()
    await expect(list.locator("li").first()).toHaveAttribute("draggable", "false")
})


test("Current Work shows its linked global row and tracks reordering, search and refresh", async ({ page }) => {
    await page.setViewportSize({ width: 1280, height: 1100 })
    await seed(page, 4)
    const current = page.getByRole("region", { name: "Current Work", exact: true })
    await expect(current.locator(".project-order-number")).toHaveCount(0)
    page.once("dialog", dialog => dialog.accept())
    await page.getByRole("button", { name: "Open Example 3", exact: true }).click()
    await expect(current.locator(".project-order-number")).toHaveText("3.")
    await page.getByRole("button", { name: "Reorder saved work" }).click()
    await page.getByRole("button", { name: "Move Example 3 to top", exact: true }).click()
    await expect(current.locator(".project-order-number")).toHaveText("1.")
    await page.getByRole("button", { name: "Reorder saved work" }).click()
    await page.getByRole("searchbox", { name: "Search saved work" }).fill("Example 4")
    await expect(current.locator(".project-order-number")).toHaveText("1.")
    await page.reload()
    await expect(current.locator(".project-order-number")).toHaveText("1.")
    page.once("dialog", dialog => dialog.accept())
    await page.getByRole("button", { name: "Delete Example 3", exact: true }).click()
    await expect(current.locator(".project-order-number")).toHaveCount(0)
    await expect(page.getByRole("textbox", { name: "HTML code editor" })).toHaveText("")
})
