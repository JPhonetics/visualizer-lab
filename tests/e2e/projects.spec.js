import { expect, test } from "@playwright/test"

const htmlEditor = page => page.getByRole("textbox", { name: "HTML code editor" })
const saveCopy = async (page) => {
    await page.getByRole("button", { name: "Save As", exact: true }).click()
    await page.getByRole("button", { name: "Create copy", exact: true }).click()
}
const accept = page => page.once("dialog", dialog => dialog.accept())
const rename = async (page, button, name) => {
    await page.getByRole("button", { name: button, exact: true }).dblclick()
    await page.getByRole("textbox", { name: button, exact: true }).fill(name)
    await page.getByRole("button", { name: "Apply", exact: true }).click()
}

test("Current Work survives immediate refresh; named copies open, rename, search and delete safely", async ({ page }) => {
    await page.goto("/frontend")
    await htmlEditor(page).fill("<h1>Saved original</h1>")
    await page.getByRole("tab", { name: "CSS", exact: true }).click()
    await page.getByRole("textbox", { name: "CSS code editor" }).fill("h1 { color: green; }")
    await page.getByRole("tab", { name: "JavaScript", exact: true }).click()
    await page.getByRole("textbox", { name: "JavaScript code editor" }).fill('document.body.dataset.restored = "yes"')
    await page.reload()
    await expect(htmlEditor(page)).toHaveText("<h1>Saved original</h1>")
    await expect(page.frameLocator(".preview-frame").locator("body")).toHaveAttribute("data-restored", "yes")
    await expect(page.frameLocator(".preview-frame").getByRole("heading")).toHaveCSS("color", "rgb(0, 128, 0)")
    await rename(page, "Rename current work", "Example")
    await saveCopy(page)
    await expect(page.getByRole("button", { name: "Open Example", exact: true })).toBeVisible()
    await htmlEditor(page).fill("changed draft")
    page.once("dialog", dialog => dialog.dismiss())
    await page.getByRole("button", { name: "Open Example", exact: true }).click()
    await expect(htmlEditor(page)).toHaveText("changed draft")
    accept(page)
    await page.getByRole("button", { name: "Open Example", exact: true }).click()
    await expect(htmlEditor(page)).toHaveText("<h1>Saved original</h1>")
    await htmlEditor(page).focus()
    await page.keyboard.press("ControlOrMeta+z")
    await expect(htmlEditor(page)).toHaveText("<h1>Saved original</h1>")
    await rename(page, "Rename Example", "Named copy")
    await page.getByRole("searchbox", { name: "Search saved work" }).fill("missing")
    await expect(page.getByText("No matching saved work.")).toBeVisible()
    await page.getByRole("searchbox", { name: "Search saved work" }).fill("named")
    await expect(page.getByRole("button", { name: "Open Named copy" })).toBeVisible()
    page.once("dialog", dialog => dialog.dismiss())
    await page.getByRole("button", { name: "Delete Named copy" }).click()
    await expect(page.getByRole("button", { name: "Open Named copy" })).toBeVisible()
    accept(page)
    await page.getByRole("button", { name: "Delete Named copy" }).click()
    await expect(page.getByRole("button", { name: "Open Named copy" })).toHaveCount(0)
    await expect(page.getByRole("heading", { name: "Saved Work", exact: true })).toBeFocused()
    await expect(htmlEditor(page)).toHaveText("<h1>Saved original</h1>")
    accept(page)
    await page.getByRole("button", { name: "New work", exact: true }).click()
    await expect(htmlEditor(page)).toHaveText("")
    await page.reload()
    await expect(htmlEditor(page)).toHaveText("")
})

test("a second workspace pauses saving when another tab writes", async ({ page, context }) => {
    await page.goto("/frontend")
    const second = await context.newPage()
    await second.goto("/frontend")
    await htmlEditor(page).fill("first tab wins")
    await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem("visualizerLab.projects.v1"))?.draft.sources.html)).toBe("first tab wins")
    await expect(second.getByRole("alert")).toContainText("another tab")
    await htmlEditor(second).fill("second tab stays in memory")
    await expect(second.getByRole("button", { name: "Retry saving" })).toHaveCount(0)
    await expect(htmlEditor(second)).toHaveText("second tab stays in memory")
    await page.reload()
    await expect(htmlEditor(page)).toHaveText("first tab wins")
})

test("corrupt stored data is preserved while editing remains available", async ({ page }) => {
    await page.addInitScript(() => localStorage.setItem("visualizerLab.projects.v1", "{unreadable"))
    await page.goto("/frontend")
    await expect(page.getByRole("alert")).toContainText("Stored data was preserved")
    await htmlEditor(page).fill("temporary editing")
    await saveCopy(page)
    expect(await page.evaluate(() => localStorage.getItem("visualizerLab.projects.v1"))).toBe("{unreadable")
    await expect(page.frameLocator(".preview-frame").locator("body")).toContainText("temporary editing")
})

test("inline rename works without prompts and Save changes updates the opened copy", async ({ page }) => {
    await page.goto("/frontend")
    await expect(page.getByRole("button", { name: "Save", exact: true })).toBeEnabled()
    await htmlEditor(page).fill("original")
    await rename(page, "Rename current work", "Original")
    await saveCopy(page)
    await rename(page, "Rename Original", "Saved example")
    await expect(page.getByRole("button", { name: "Open Saved example", exact: true })).toBeVisible()
    await page.getByRole("button", { name: "Rename current work" }).dblclick()
    await expect(page.getByRole("button", { name: "Rename current work", exact: true })).toHaveCount(0)
    await page.getByRole("textbox", { name: "Rename current work" }).fill("Canceled")
    await page.getByRole("textbox", { name: "Rename current work" }).press("Escape")
    await expect(page.getByRole("button", { name: "Rename current work" })).toBeFocused()
    accept(page)
    await page.getByRole("button", { name: "Open Saved example", exact: true }).click()
    await htmlEditor(page).fill("updated saved source")
    await page.getByRole("button", { name: "Save", exact: true }).click()
    await expect(page.locator(".saved-projects > li")).toHaveCount(1)
    await page.reload()
    await expect(htmlEditor(page)).toHaveText("updated saved source")
    await expect(page.getByRole("button", { name: "Save", exact: true })).toBeEnabled()
    accept(page)
    await page.getByRole("button", { name: "New work", exact: true }).click()
    accept(page)
    await page.getByRole("button", { name: "Open Saved example", exact: true }).click()
    await expect(htmlEditor(page)).toHaveText("updated saved source")
    await page.setViewportSize({ width: 700, height: 700 })
    await expect(page.getByRole("button", { name: "Rename Saved example", exact: true })).toBeVisible()
    const rows = await page.locator(".saved-projects > li").boundingBox()
    expect(rows.height).toBeLessThan(65)
})


test("Save works for unlinked work and Save As creates a named independent copy", async ({ page }) => {
    await page.goto("/frontend")
    await htmlEditor(page).fill("first saved text")
    await page.getByRole("button", { name: "Save", exact: true }).click()
    await expect(page.locator(".saved-projects > li")).toHaveCount(1)
    await expect(page.locator(".saved-projects time")).toContainText("Last edited:")
    const draftTime = page.getByRole("region", { name: "Current Work", exact: true }).locator("time")
    await expect(draftTime).toContainText("Last edited:")
    const savedTime = await page.locator(".saved-projects time").getAttribute("datetime")
    await htmlEditor(page).fill("updated with Save")
    await expect.poll(() => draftTime.getAttribute("datetime")).not.toBe(savedTime)
    await expect(page.locator(".saved-projects time")).toHaveAttribute("datetime", savedTime)
    await page.getByRole("button", { name: "Save", exact: true }).click()
    await expect(page.locator(".saved-projects > li")).toHaveCount(1)
    await page.getByRole("button", { name: "Save As", exact: true }).click()
    await page.getByRole("textbox", { name: "New copy name" }).fill("Other copy")
    await page.getByRole("button", { name: "Cancel", exact: true }).click()
    await expect(page.locator(".saved-projects > li")).toHaveCount(1)
    await page.getByRole("button", { name: "Save As", exact: true }).click()
    await page.getByRole("textbox", { name: "New copy name" }).fill("Other copy")
    await page.getByRole("button", { name: "Create copy", exact: true }).click()
    await expect(page.locator(".saved-projects > li")).toHaveCount(2)
    const currentName = page.getByRole("button", { name: "Rename current work", exact: true })
    await currentName.click()
    await expect(page.getByRole("textbox", { name: "Rename current work", exact: true })).toHaveCount(0)
    await currentName.press("Enter")
    await page.getByRole("textbox", { name: "Rename current work", exact: true }).fill("Keyboard rename")
    await page.getByRole("textbox", { name: "Rename current work", exact: true }).press("Enter")
    await expect(currentName).toHaveText("Keyboard rename")
    await page.getByRole("button", { name: "Save", exact: true }).click()
    await expect(page.getByRole("button", { name: "Open Keyboard rename", exact: true })).toBeVisible()
    accept(page)
    await page.getByRole("button", { name: "Open Untitled", exact: true }).click()
    await expect(htmlEditor(page)).toHaveText("updated with Save")
})
